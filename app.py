# 3-RUN — МҰҒАЛІМ ПАНЕЛІ: K-MEANS → ТҮЗЕТУ ТОПТАРЫ → EXCEL
import numpy as np
import matplotlib.pyplot as plt
from sklearn.cluster import KMeans
from sklearn.preprocessing import StandardScaler
from sklearn.decomposition import PCA
from openpyxl import load_workbook
from openpyxl.styles import Font, Alignment
from openpyxl.utils import get_column_letter

def teacher_ml_report(grade=None, bzhb=None):
    if not os.path.exists(DRIVE_RESULT_FILE):
        print("⚠️ Әзірге нақты нәтиже жоқ. Алдымен оқушылар БЖБ орындасын."); return None
    df=pd.read_csv(DRIVE_RESULT_FILE)
    if grade: df=df[df["Сынып"].astype(str)==grade]
    if bzhb: df=df[df["БЖБ"].astype(str)==bzhb]
    df=df.copy().reset_index(drop=True)
    if len(df)<2:
        print("⚠️ K-means үшін кемінде 2 оқушының нәтижесі керек."); return None
    goal_cols=[c for c in df.columns if re.fullmatch(r"\d+\.\d+\.\d+\.\d+",str(c)) and pd.to_numeric(df[c],errors="coerce").notna().any()]
    # Таңдалған сынып/БЖБ-да мәні бар мақсаттарды ғана аламыз
    goal_cols=[c for c in goal_cols if pd.to_numeric(df[c],errors="coerce").notna().any()]
    if not goal_cols:
        print("⚠️ Оқу мақсаттары бойынша сандық дерек табылмады."); return None
    X=df[goal_cols].apply(pd.to_numeric,errors="coerce")
    # Бұл БЖБ-ға қатысы жоқ бос бағандарды 0 деп жазбаймыз; баған орташа мәнімен толтырамыз
    X=X.fillna(X.mean()).fillna(0)
    n_clusters=min(3,len(df)) if len(df)>=3 else 2
    scaled=StandardScaler().fit_transform(X)
    labels=KMeans(n_clusters=n_clusters,random_state=42,n_init=10).fit_predict(scaled)+1
    df["Түзету тобы"]=labels
    print("🧠 K-MEANS БОЙЫНША ТҮЗЕТУ ТОПТАРЫ")
    print("="*60)
    for cl in sorted(df["Түзету тобы"].unique()):
        group=df[df["Түзету тобы"]==cl]; av=group[goal_cols].mean(); weak=av[av<60].sort_values()
        print(f"\n👥 {cl}-ТОП: "+", ".join(group["Оқушы"].astype(str)))
        if len(weak):
            print("🔴 Ортақ олқылықтар:")
            for g,v in weak.items(): print(f" • {g} — {round(v)}%")
            print("💡 Ұсыныс: осы мақсаттар бойынша шағын топтық түзету жұмысын өткізу.")
        else:
            print("🟢 60%-дан төмен ортақ олқылық жоқ. Бекіту/күрделендірілген тапсырма беруге болады.")
    if X.shape[1]>=2:
        pts=PCA(n_components=2).fit_transform(scaled)
        plt.figure(figsize=(10,7)); plt.scatter(pts[:,0],pts[:,1],c=labels,s=140)
        for i,n in enumerate(df["Оқушы"]): plt.annotate(str(n),(pts[i,0],pts[i,1]),xytext=(5,5),textcoords="offset points")
        plt.title("Оқушылардың білім олқылықтары бойынша топталуы"); plt.xlabel("1-компонент"); plt.ylabel("2-компонент"); plt.grid(alpha=.3); plt.show()
    # Әр оқушыға ұсыныс
    def rec(row):
        weak=[g for g in goal_cols if pd.notna(row.get(g)) and float(row[g])<60]
        return "Бекіту және күрделендірілген тапсырмалар" if not weak else "Түзету қажет: "+", ".join(weak)
    df["Ұсыныс"]=df.apply(rec,axis=1)
    summary=df.groupby("Түзету тобы")[goal_cols].mean().round(1).reset_index()
    summary["Оқушы саны"]=df.groupby("Түзету тобы").size().values
    out=os.path.join(PROJECT_FOLDER,"BZHB_ML_mugalim_esebi.xlsx")
    with pd.ExcelWriter(out,engine="openpyxl") as w:
        df.to_excel(w,sheet_name="Оқушылар нәтижесі",index=False)
        summary.to_excel(w,sheet_name="Түзету топтары",index=False)
    wb=load_workbook(out)
    for ws in wb.worksheets:
        for c in ws[1]: c.font=Font(bold=True); c.alignment=Alignment(horizontal="center",vertical="center")
        for col in ws.columns:
            letter=get_column_letter(col[0].column); width=min(max(len(str(c.value or "")) for c in col)+3,45); ws.column_dimensions[letter].width=width
        ws.freeze_panes="A2"
    wb.save(out)
    print("\n✅ Excel есебі дайын:",out)

    return df,out


