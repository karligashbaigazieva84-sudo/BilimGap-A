def check_one_answer(answer, question):
    answer = str(answer or "").lower().strip()
    if not answer:
        return 0
    max_score = question["score"]
    if "answer" in question:
        correct = str(question["answer"]).lower().strip()
        return max_score if correct in answer else 0
    keywords = [str(x).lower() for x in question.get("keywords", [])]
    found = sum(1 for word in keywords if word in answer)
    need = question.get("min_keywords", 2)
    if found >= need:
        return max_score
    if found >= 1:
        return max(1, max_score // 2)
    return 0

